package dev.vfyjxf.taffy.tree.grid;

import dev.vfyjxf.taffy.geometry.TaffyLine;
import dev.vfyjxf.taffy.style.GridPlacement;
import dev.vfyjxf.taffy.style.GridRepetition;
import dev.vfyjxf.taffy.style.GridTemplateArea;
import dev.vfyjxf.taffy.style.GridTemplateComponent;
import dev.vfyjxf.taffy.style.NamedGridLine;
import dev.vfyjxf.taffy.style.TaffyStyle;

import java.util.ArrayList;
import java.util.HashMap;
import java.util.List;
import java.util.Map;

/**
 * Resolves named grid lines and named grid area edges to numeric line indices.
 * <p>
 * The resolver keeps three independent lookups, mirroring upstream taffy's
 * {@code NamedLineResolver} (GR-15 / #1264 / #1258):
 * <ol>
 *   <li>explicit line names declared in the track template ({@code grid-template-columns/rows},
 *       including the positional names carried by a {@code repeat()} &mdash; GR-17 / #1035);</li>
 *   <li>the edges of named grid areas ({@code grid-template-areas} and explicitly named
 *       {@code <area>-start}/{@code <area>-end} lines) in a separate area table. Area edges are
 *       <em>not</em> materialised as "{@code name-start}"/"{@code name-end}" strings in the line
 *       name maps: they are only matched by a bare {@code <custom-ident>} (or by an explicit
 *       {@code <area>-start}/{@code <area>-end} line name);</li>
 *   <li>the number of explicit tracks in each axis, used for negative line numbers and for the
 *       implicit-line fallback of a non-existent named line.</li>
 * </ol>
 * <p>
 * Lookups are performed in OriginZero coordinates and the result is converted back to a CSS grid
 * line number; every computed line is clamped into the limited grid
 * {@code [-MAX_GRID_TRACKS, MAX_GRID_TRACKS]} (upstream {@code OriginZeroLine::clamped}), which
 * also fixes the numbering underflow of the previous implementation (GR-17 / #1035).
 * <p>
 * Line positions are stored as 1-based "CSS Grid Line" numbers (the coordinate system used by
 * {@code grid-row}/{@code grid-column}, where {@code 1} is the first explicit line and {@code -1}
 * the last one). Named placements are resolved exactly once, before the grid size estimate, and
 * the resolved numeric placements are what the grid placement pass consumes (GR-15 / #1259).
 * <p>
 * Corresponds to Rust's NamedLineResolver in taffy/src/compute/grid/types/named.rs.
 */
public final class NamedLineResolver {

    /** The maximum number of tracks in each direction from the start of the explicit grid. */
    private static final int MAX_GRID_TRACKS = 10_000;

    /** The lowest valid grid line in OriginZero coordinates */
    private static final int MIN_OZ_LINE = -MAX_GRID_TRACKS;

    /** The highest valid grid line in OriginZero coordinates */
    private static final int MAX_OZ_LINE = MAX_GRID_TRACKS;

    /** Map of row line names to their one-based line positions. Each name may have multiple lines. */
    private final Map<String, List<Integer>> rowLines;

    /** Map of column line names to their one-based line positions. Each name may have multiple lines. */
    private final Map<String, List<Integer>> columnLines;

    /**
     * Map of area names to the first line that starts/ends the area in each axis (0 = no such
     * line). This is where the {@code <area>-start}/{@code <area>-end} line names generated by
     * {@code grid-template-areas} are represented.
     */
    private final Map<String, AreaLines> areas;

    /** Number of columns implied by grid area definitions */
    private int areaColumnCount;

    /** Number of rows implied by grid area definitions */
    private int areaRowCount;

    /** The number of explicit columns in the grid (set after track expansion) */
    private int explicitColumnCount;

    /** The number of explicit rows in the grid (set after track expansion) */
    private int explicitRowCount;

    /**
     * Create a new NamedLineResolver from container style.
     * <p>
     * Auto-repetitions are assumed to be expanded once, which matches the previous behaviour of
     * the resolver when called without the auto-repetition counts. Prefer
     * {@link #NamedLineResolver(TaffyStyle, int, int)} so that the line names of tracks generated
     * by {@code repeat(auto-fill/auto-fit, ...)} are numbered identically to the expanded template.
     *
     * @param style The grid container's style
     */
    public NamedLineResolver(TaffyStyle style) {
        this(style, 1, 1);
    }

    /**
     * Create a new NamedLineResolver from container style.
     *
     * @param style                   The grid container's style
     * @param columnAutoRepetitions   The number of times the column axis' auto-repetition is
     *                                expanded (0 if there is none)
     * @param rowAutoRepetitions      The number of times the row axis' auto-repetition is expanded
     *                                (0 if there is none)
     */
    public NamedLineResolver(TaffyStyle style, int columnAutoRepetitions, int rowAutoRepetitions) {
        this.rowLines = new HashMap<>();
        this.columnLines = new HashMap<>();
        this.areas = new HashMap<>();
        this.areaColumnCount = 0;
        this.areaRowCount = 0;
        this.explicitColumnCount = 0;
        this.explicitRowCount = 0;

        // The size of the area template may be larger than the extents of the named areas due to
        // unnamed (".") cells; the Java API only exposes the named areas, so the extents are
        // derived from them (upstream keeps the template size on the style).
        if (style.gridTemplateAreas != null) {
            for (GridTemplateArea area : style.gridTemplateAreas) {
                areas.put(area.getName(), new AreaLines(
                    area.getRowStart(), area.getRowEnd(), area.getColumnStart(), area.getColumnEnd()));
                areaColumnCount = Math.max(areaColumnCount, Math.max(1, area.getColumnEnd()) - 1);
                areaRowCount = Math.max(areaRowCount, Math.max(1, area.getRowEnd()) - 1);
            }
        }

        // Explicit line names. The Java style API is a flattened (name, line) list rather than
        // upstream's positional per-line name sets, so the line number is taken from the entry.
        if (style.gridTemplateColumnNames != null) {
            for (NamedGridLine namedLine : style.gridTemplateColumnNames) {
                upsertLineName(columnLines, areas, Axis.COLUMN, namedLine.getName(), namedLine.getIndex());
            }
        }
        ingestRepeatLineNames(style.gridTemplateColumnsWithRepeat, columnAutoRepetitions,
            columnLines, areas, Axis.COLUMN);

        if (style.gridTemplateRowNames != null) {
            for (NamedGridLine namedLine : style.gridTemplateRowNames) {
                upsertLineName(rowLines, areas, Axis.ROW, namedLine.getName(), namedLine.getIndex());
            }
        }
        ingestRepeatLineNames(style.gridTemplateRowsWithRepeat, rowAutoRepetitions,
            rowLines, areas, Axis.ROW);

        // Sort and dedup lines for consistent lookup
        sortAndDedup(columnLines);
        sortAndDedup(rowLines);
    }

    private static void sortAndDedup(Map<String, List<Integer>> lineNames) {
        for (List<Integer> lines : lineNames.values()) {
            lines.sort(Integer::compareTo);
            for (int i = lines.size() - 1; i > 0; i--) {
                if (lines.get(i).equals(lines.get(i - 1))) {
                    lines.remove(i);
                }
            }
        }
    }

    /**
     * Add a line name to a line name map, deriving the area edge of a
     * {@code <area>-start}/{@code <area>-end} name on the way (upstream
     * {@code upsert_line_name_map}). The area table is updated with the smallest line that carries
     * the edge name; when the line name map has no entry for the name yet, the area's own edge line
     * is seeded into it so that an explicitly named line is merged with the area's edge.
     */
    private static void upsertLineName(Map<String, List<Integer>> lineNames, Map<String, AreaLines> areas,
                                       Axis axis, String name, int line) {
        if (name == null || name.isEmpty()) {
            return;
        }

        int areaLine = 0;
        AreaEdge edge = splitAreaEdgeName(name);
        if (edge != null && line > 0) {
            AreaLines areaLines = areas.get(edge.areaName());
            if (areaLines == null) {
                areaLines = new AreaLines();
                areas.put(edge.areaName(), areaLines);
            }
            areaLine = areaLines.line(axis, edge.end());
            areaLines.upsert(axis, edge.end(), line);
        }

        List<Integer> lines = lineNames.get(name);
        if (lines == null) {
            lines = new ArrayList<>(2);
            if (areaLine != 0) {
                lines.add(areaLine);
            }
            lineNames.put(name, lines);
        }
        lines.add(line);
    }

    /**
     * Register the positional line names carried by {@code repeat()} components
     * (GR-17 / #1035).
     * <p>
     * Line name sets are positional: set {@code i} names the {@code i}th line of each repetition,
     * and the last set of a repetition collapses with the first set of the following repetition
     * (or of the following template component). An empty list means the repetition's lines are
     * unnamed; any other length must be exactly {@code trackCount + 1}.
     */
    private static void ingestRepeatLineNames(List<GridTemplateComponent> template,
                                              int autoRepetitions,
                                              Map<String, List<Integer>> lineNames,
                                              Map<String, AreaLines> areas,
                                              Axis axis) {
        if (template == null || template.isEmpty()) {
            return;
        }

        // 1-based CSS line number of the start edge of the next template component.
        int currentLine = 1;
        for (GridTemplateComponent component : template) {
            if (component == null) {
                continue;
            }
            if (component.isSingle()) {
                currentLine += 1;
                continue;
            }
            GridRepetition repeat = component.getRepeat();
            if (repeat == null) {
                continue;
            }

            int linesPerRepetition = repeat.getTrackCount();
            int repetitions = repeat.isAutoRepetition()
                ? Math.max(0, autoRepetitions)
                : Math.max(0, repeat.getCount());

            List<List<String>> nameSets = repeat.getLineNames();
            if (!nameSets.isEmpty() && nameSets.size() != linesPerRepetition + 1) {
                throw new IllegalArgumentException(
                    "grid template repetition must have no line name sets or exactly track count + 1 of them ("
                    + linesPerRepetition + " tracks but " + nameSets.size() + " line name sets)");
            }

            for (int repetition = 0; repetition < repetitions; repetition++) {
                for (int i = 0; i < nameSets.size(); i++) {
                    int line = currentLine + i;
                    for (String name : nameSets.get(i)) {
                        upsertLineName(lineNames, areas, axis, name, line);
                    }
                }
                currentLine += linesPerRepetition;
                // Names for lines beyond the maximum track limit are never resolvable: the explicit
                // grid is clamped to MAX_GRID_TRACKS.
                if (currentLine > MAX_GRID_TRACKS) {
                    return;
                }
            }
        }
    }

    /**
     * Resolve named lines in a row placement to numeric lines.
     * @param placement The row placement (start and end)
     * @return Line with resolved GridPlacements (NAMED_LINE -> LINE, NAMED_SPAN resolved against anchor)
     */
    public TaffyLine<GridPlacement> resolveRowNames(TaffyLine<GridPlacement> placement) {
        return resolveLineNames(placement, Axis.ROW);
    }

    /**
     * Resolve named lines in a column placement to numeric lines.
     * @param placement The column placement (start and end)
     * @return Line with resolved GridPlacements (NAMED_LINE -> LINE, NAMED_SPAN resolved against anchor)
     */
    public TaffyLine<GridPlacement> resolveColumnNames(TaffyLine<GridPlacement> placement) {
        return resolveLineNames(placement, Axis.COLUMN);
    }

    private enum Axis { ROW, COLUMN }
    private enum End { START, END }

    /**
     * Resolve named lines for both start and end of a grid placement, mirroring upstream
     * {@code NamedLineResolverAxis::resolve_line_names}.
     */
    private TaffyLine<GridPlacement> resolveLineNames(TaffyLine<GridPlacement> line, Axis axis) {
        GridPlacement start = (line.start != null) ? line.start : GridPlacement.auto();
        GridPlacement end = (line.end != null) ? line.end : GridPlacement.auto();

        GridPlacement resolvedStart = start.isNamedLine()
            ? GridPlacement.line(findNamedLine(start, End.START, axis))
            : start;
        GridPlacement resolvedEnd = end.isNamedLine()
            ? GridPlacement.line(findNamedLine(end, End.END, axis))
            : end;

        // If both the *-start and *-end values of its grid-placement properties specify a line, its
        // grid span is implicit. If it has an explicit span value, its grid span is explicit.
        // Otherwise its grid span is automatic:
        //   - if it is subgridded in that axis, its grid span is determined from its <line-name-list>;
        //   - otherwise its grid span is 1.
        // https://drafts.csswg.org/css-grid-2/#grid-span
        if (resolvedStart.isLine() && resolvedStart.getLineNumber() != 0 && resolvedEnd.isNamedSpan()) {
            int afterStartLine = intoOriginZeroLine(resolvedStart.getLineNumber(), axis) + 1;
            int endLine = nthLineForwards(
                linesNamed(resolvedEnd.getLineName(), axis),
                afterStartLine,
                Math.max(1, resolvedEnd.getValue()),
                axis);
            return new TaffyLine<>(resolvedStart, GridPlacement.line(intoGridLine(endLine, axis)));
        }

        if (resolvedStart.isNamedSpan() && resolvedEnd.isLine() && resolvedEnd.getLineNumber() != 0) {
            int beforeEndLine = intoOriginZeroLine(resolvedEnd.getLineNumber(), axis) - 1;
            int startLine = nthLineBackwards(
                linesNamed(resolvedStart.getLineName(), axis),
                beforeEndLine,
                Math.max(1, resolvedStart.getValue()),
                axis);
            return new TaffyLine<>(GridPlacement.line(intoGridLine(startLine, axis)), resolvedEnd);
        }

        // A named span paired with auto or with another named span behaves as span(1).
        GridPlacement startResult = resolvedStart.isNamedSpan() ? GridPlacement.span(1) : resolvedStart;
        GridPlacement endResult = resolvedEnd.isNamedSpan() ? GridPlacement.span(1) : resolvedEnd;
        return new TaffyLine<>(startResult, endResult);
    }

    /**
     * Resolve the grid line for a named grid line ({@code <custom-ident>} or
     * {@code <integer> <custom-ident>}), mirroring upstream {@code find_named_line}.
     * <p>
     * A bare {@code <custom-ident>} (a placement created with
     * {@link GridPlacement#namedLine(String)}) first attempts to match the edge of a named grid
     * area: the first line named {@code <custom-ident>-start} (or {@code <custom-ident>-end} for an
     * end line). An explicit index (created with {@link GridPlacement#namedLine(String, int)})
     * never matches an area edge.
     * <p>
     * https://drafts.csswg.org/css-grid-2/#line-placement
     */
    private int findNamedLine(GridPlacement placement, End end, Axis axis) {
        String name = placement.getLineName();
        if (name == null) {
            name = "";
        }
        int idx = placement.isBareName() ? 0 : placement.getNthIndex();

        if (idx == 0) {
            int areaLine = areaLine(name, end, axis);
            if (areaLine != 0) {
                return intoGridLine(clampOzLine(ozLine(areaLine)), axis);
            }
        }

        List<Integer> lines = linesNamed(name, axis);
        int line = (idx >= 0)
            ? nthLineForwards(lines, 0, Math.max(idx, 1), axis)
            // Negate in a wider type so that Integer.MIN_VALUE cannot wrap (upstream casts the
            // i16 index to i32 before negating).
            : nthLineBackwards(lines, explicitTrackCount(axis), (int) Math.min(Integer.MAX_VALUE, -(long) idx), axis);
        return intoGridLine(line, axis);
    }

    /**
     * The sorted line numbers of the lines with the passed name.
     * <p>
     * A line generated by a grid area is included in the lines of its name if any line has been
     * explicitly given the same name. Otherwise it is found from the area's edges (which is how an
     * explicit {@code <area>-start}/{@code <area>-end} placement still resolves to the area edge).
     */
    private List<Integer> linesNamed(String name, Axis axis) {
        Map<String, List<Integer>> lineNameMap = lineNameMap(axis);
        List<Integer> lines = (name != null) ? lineNameMap.get(name) : null;
        if (lines != null) {
            return lines;
        }
        AreaEdge edge = splitAreaEdgeName(name);
        if (edge != null) {
            int areaLine = areaLine(edge.areaName(), edge.end(), axis);
            if (areaLine != 0) {
                return List.of(areaLine);
            }
        }
        return List.of();
    }

    /**
     * Find the {@code n}th line in {@code lines} (searching forwards) that is not before
     * {@code firstLine}.
     * <p>
     * If there are not enough such lines, then all implicit lines after the explicit grid are
     * assumed to be in {@code lines} for the purpose of counting.
     * <p>
     * https://drafts.csswg.org/css-grid-2/#grid-placement-int
     */
    private int nthLineForwards(List<Integer> lines, int firstLine, int n, Axis axis) {
        int first = Math.max(0, firstLine);
        int start = 0;
        while (start < lines.size() && ozLine(lines.get(start)) < first) {
            start++;
        }
        int available = lines.size() - start;
        if (n >= 1 && n <= available) {
            return clampOzLine(ozLine(lines.get(start + n - 1)));
        }
        long base = Math.max(first, (long) explicitTrackCount(axis) + 1);
        return clampOzLine(base + ((long) n - available) - 1);
    }

    /**
     * Find the {@code n}th line in {@code lines} (searching backwards) that is not after
     * {@code lastLine}.
     * <p>
     * If there are not enough such lines, then all implicit lines before the explicit grid are
     * assumed to be in {@code lines} for the purpose of counting.
     * <p>
     * https://drafts.csswg.org/css-grid-2/#grid-placement-int
     */
    private int nthLineBackwards(List<Integer> lines, int lastLine, int n, Axis axis) {
        int last = Math.min(lastLine, explicitTrackCount(axis));
        int end = 0;
        while (end < lines.size() && ozLine(lines.get(end)) <= last) {
            end++;
        }
        int available = end;
        if (n >= 1 && n <= available) {
            return clampOzLine(ozLine(lines.get(available - n)));
        }
        long base = Math.min(last, -1);
        return clampOzLine(base - ((long) n - available) + 1);
    }

    /** The origin-zero position of the end edge of the explicit grid. */
    private int explicitTrackCount(Axis axis) {
        return (axis == Axis.ROW) ? explicitRowCount : explicitColumnCount;
    }

    /** The line for the passed edge of the named grid area in this axis (0 if there is none). */
    private int areaLine(String areaName, End end, Axis axis) {
        if (areaName == null) {
            return 0;
        }
        AreaLines areaLines = areas.get(areaName);
        return (areaLines != null) ? areaLines.line(axis, end) : 0;
    }

    private Map<String, List<Integer>> lineNameMap(Axis axis) {
        return (axis == Axis.ROW) ? rowLines : columnLines;
    }

    /** Convert a 1-based "CSS Grid Line" number to OriginZero coordinates. */
    private static int ozLine(int gridLine) {
        return gridLine - 1;
    }

    /**
     * Convert a "CSS Grid Line" number to OriginZero coordinates using the explicit track count,
     * clamping into the limited grid (upstream {@code GridLine::into_origin_zero_line}).
     */
    private int intoOriginZeroLine(int gridLine, Axis axis) {
        long explicitLineCount = (long) explicitTrackCount(axis) + 1;
        long oz = (gridLine > 0) ? (long) gridLine - 1 : (long) gridLine + explicitLineCount;
        return clampOzLine(oz);
    }

    /**
     * Convert an OriginZero line to a "CSS Grid Line" number using the explicit track count
     * (the inverse of {@link #intoOriginZeroLine}; upstream {@code OriginZeroLine::into_grid_line}).
     */
    private int intoGridLine(int oz, Axis axis) {
        long explicitLineCount = (long) explicitTrackCount(axis) + 1;
        long gridLine = (oz >= 0) ? (long) oz + 1 : (long) oz - explicitLineCount;
        return (int) Math.max(Integer.MIN_VALUE, Math.min(Integer.MAX_VALUE, gridLine));
    }

    /** Clamp an OriginZero line into the limited grid. */
    private static int clampOzLine(long line) {
        return (int) Math.max(MIN_OZ_LINE, Math.min(MAX_OZ_LINE, line));
    }

    /** A {@code <area>-start}/{@code <area>-end} line name split into the area name and edge. */
    private record AreaEdge(String areaName, End end) {}

    private static AreaEdge splitAreaEdgeName(String name) {
        if (name == null) {
            return null;
        }
        if (name.endsWith("-start")) {
            return new AreaEdge(name.substring(0, name.length() - "-start".length()), End.START);
        }
        if (name.endsWith("-end")) {
            return new AreaEdge(name.substring(0, name.length() - "-end".length()), End.END);
        }
        return null;
    }

    /**
     * The first line that starts/ends an area in each axis (0 means that there is no such line).
     */
    private static final class AreaLines {
        private int rowStart;
        private int rowEnd;
        private int columnStart;
        private int columnEnd;

        AreaLines() {
        }

        AreaLines(int rowStart, int rowEnd, int columnStart, int columnEnd) {
            this.rowStart = rowStart;
            this.rowEnd = rowEnd;
            this.columnStart = columnStart;
            this.columnEnd = columnEnd;
        }

        int line(Axis axis, End end) {
            if (axis == Axis.ROW) {
                return (end == End.START) ? rowStart : rowEnd;
            }
            return (end == End.START) ? columnStart : columnEnd;
        }

        /** Record a line as the edge, keeping the smallest line that carries the edge name. */
        void upsert(Axis axis, End end, int line) {
            int current = line(axis, end);
            int updated = (current == 0) ? line : Math.min(current, line);
            if (axis == Axis.ROW) {
                if (end == End.START) {
                    rowStart = updated;
                } else {
                    rowEnd = updated;
                }
            } else {
                if (end == End.START) {
                    columnStart = updated;
                } else {
                    columnEnd = updated;
                }
            }
        }
    }

    /**
     * Get the number of columns defined by grid areas.
     */
    public int getAreaColumnCount() {
        return areaColumnCount;
    }

    /**
     * Get the number of rows defined by grid areas.
     */
    public int getAreaRowCount() {
        return areaRowCount;
    }

    /**
     * Set the number of explicit columns (call after track expansion).
     */
    public void setExplicitColumnCount(int count) {
        this.explicitColumnCount = count;
    }

    /**
     * Set the number of explicit rows (call after track expansion).
     */
    public void setExplicitRowCount(int count) {
        this.explicitRowCount = count;
    }

    /**
     * Get the number of explicit columns.
     */
    public int getExplicitColumnCount() {
        return explicitColumnCount;
    }

    /**
     * Get the number of explicit rows.
     */
    public int getExplicitRowCount() {
        return explicitRowCount;
    }

    /**
     * Check if there are any named lines or areas defined.
     */
    public boolean hasNamedLines() {
        return !rowLines.isEmpty() || !columnLines.isEmpty() || !areas.isEmpty();
    }

    @Override
    public String toString() {
        StringBuilder sb = new StringBuilder();
        sb.append("NamedLineResolver {\n");

        if (!areas.isEmpty()) {
            sb.append("  Areas:\n");
            for (Map.Entry<String, AreaLines> entry : areas.entrySet()) {
                AreaLines area = entry.getValue();
                sb.append("    ").append(entry.getKey())
                  .append(": row ").append(area.rowStart).append("/").append(area.rowEnd)
                  .append(", col ").append(area.columnStart).append("/").append(area.columnEnd)
                  .append("\n");
            }
        }

        if (!rowLines.isEmpty()) {
            sb.append("  Row Lines:\n");
            for (Map.Entry<String, List<Integer>> entry : rowLines.entrySet()) {
                sb.append("    ").append(entry.getKey()).append(": ").append(entry.getValue()).append("\n");
            }
        }

        if (!columnLines.isEmpty()) {
            sb.append("  Column Lines:\n");
            for (Map.Entry<String, List<Integer>> entry : columnLines.entrySet()) {
                sb.append("    ").append(entry.getKey()).append(": ").append(entry.getValue()).append("\n");
            }
        }

        sb.append("  Explicit: ").append(explicitColumnCount).append(" cols x ").append(explicitRowCount).append(" rows\n");
        sb.append("}");
        return sb.toString();
    }
}
