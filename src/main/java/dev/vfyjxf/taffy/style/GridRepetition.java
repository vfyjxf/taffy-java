package dev.vfyjxf.taffy.style;

import java.util.ArrayList;
import java.util.List;
import java.util.Objects;

/**
 * Represents a repeat() function in grid-template-rows or grid-template-columns.
 * Used to express: repeat(count, track-list) where count can be:
 * - A specific integer (e.g., repeat(3, 1fr))
 * - auto-fill: Fill as many tracks as possible without overflowing
 * - auto-fit: Like auto-fill but collapses empty tracks
 * <p>
 * A repetition may also carry line names for the lines it generates
 * ({@link #getLineNames()}). Line name sets are positional: set {@code i} names the {@code i}th
 * line of each repetition, and the last set of a repetition collapses with the first set of the
 * following repetition (or of the following template component). The list must either be empty
 * (the repetition's lines are unnamed) or contain exactly {@code tracks.size() + 1} sets (one per
 * line, including both edge lines; individual sets may be empty). This mirrors upstream taffy's
 * {@code GridTemplateRepetition::line_names} ({@code #1035} / GR-17).
 */
public class GridRepetition {
    
    /**
     * The type of repetition count
     */
    public enum RepetitionType {
        /** A specific integer count */
        COUNT,
        /** auto-fill: Fill as many tracks as possible */
        AUTO_FILL,
        /** auto-fit: Like auto-fill but collapses empty tracks */
        AUTO_FIT
    }
    
    private final RepetitionType type;
    private final int count;
    private final List<TrackSizingFunction> tracks;
    /**
     * Positional line names for the lines generated by a single repetition: either empty or
     * exactly {@code tracks.size() + 1} name sets. Immutable.
     */
    private final List<List<String>> lineNames;
    
    private GridRepetition(RepetitionType type, int count, List<TrackSizingFunction> tracks,
                           List<List<String>> lineNames) {
        this.type = type;
        this.count = count;
        this.tracks = new ArrayList<>(tracks);
        this.lineNames = validatedLineNames(lineNames, this.tracks.size());
    }
    
    /**
     * Creates a repeat with a specific count
     */
    public static GridRepetition count(int count, List<TrackSizingFunction> tracks) {
        return new GridRepetition(RepetitionType.COUNT, count, tracks, List.of());
    }
    
    /**
     * Creates a repeat with a specific count and positional line names.
     *
     * @param count     the repetition count
     * @param tracks    the repeated track sizing functions
     * @param lineNames either empty or exactly {@code tracks.size() + 1} positional name sets
     * @throws IllegalArgumentException if {@code lineNames} is neither empty nor
     *                                  {@code tracks.size() + 1} sets long
     */
    public static GridRepetition count(int count, List<TrackSizingFunction> tracks,
                                       List<List<String>> lineNames) {
        return new GridRepetition(RepetitionType.COUNT, count, tracks, lineNames);
    }
    
    /**
     * Creates a repeat with a specific count and a single track
     */
    public static GridRepetition count(int count, TrackSizingFunction track) {
        List<TrackSizingFunction> tracks = new ArrayList<>();
        tracks.add(track);
        return new GridRepetition(RepetitionType.COUNT, count, tracks, List.of());
    }
    
    /**
     * Creates a repeat with a specific count and a single track with positional line names
     * (two sets: the line before and the line after the repeated track).
     */
    public static GridRepetition count(int count, TrackSizingFunction track, List<List<String>> lineNames) {
        List<TrackSizingFunction> tracks = new ArrayList<>();
        tracks.add(track);
        return new GridRepetition(RepetitionType.COUNT, count, tracks, lineNames);
    }
    
    /**
     * Creates an auto-fill repeat
     */
    public static GridRepetition autoFill(List<TrackSizingFunction> tracks) {
        return new GridRepetition(RepetitionType.AUTO_FILL, 0, tracks, List.of());
    }
    
    /**
     * Creates an auto-fill repeat with positional line names.
     *
     * @param lineNames either empty or exactly {@code tracks.size() + 1} positional name sets
     * @throws IllegalArgumentException if {@code lineNames} is neither empty nor
     *                                  {@code tracks.size() + 1} sets long
     */
    public static GridRepetition autoFill(List<TrackSizingFunction> tracks, List<List<String>> lineNames) {
        return new GridRepetition(RepetitionType.AUTO_FILL, 0, tracks, lineNames);
    }
    
    /**
     * Creates an auto-fill repeat with a single track
     */
    public static GridRepetition autoFill(TrackSizingFunction track) {
        List<TrackSizingFunction> tracks = new ArrayList<>();
        tracks.add(track);
        return new GridRepetition(RepetitionType.AUTO_FILL, 0, tracks, List.of());
    }
    
    /**
     * Creates an auto-fit repeat
     */
    public static GridRepetition autoFit(List<TrackSizingFunction> tracks) {
        return new GridRepetition(RepetitionType.AUTO_FIT, 0, tracks, List.of());
    }
    
    /**
     * Creates an auto-fit repeat with positional line names.
     *
     * @param lineNames either empty or exactly {@code tracks.size() + 1} positional name sets
     * @throws IllegalArgumentException if {@code lineNames} is neither empty nor
     *                                  {@code tracks.size() + 1} sets long
     */
    public static GridRepetition autoFit(List<TrackSizingFunction> tracks, List<List<String>> lineNames) {
        return new GridRepetition(RepetitionType.AUTO_FIT, 0, tracks, lineNames);
    }
    
    /**
     * Creates an auto-fit repeat with a single track
     */
    public static GridRepetition autoFit(TrackSizingFunction track) {
        List<TrackSizingFunction> tracks = new ArrayList<>();
        tracks.add(track);
        return new GridRepetition(RepetitionType.AUTO_FIT, 0, tracks, List.of());
    }
    
    /**
     * Returns a copy of this repetition with the passed positional line names.
     *
     * @param lineNames either empty or exactly {@code tracks.size() + 1} positional name sets
     * @throws IllegalArgumentException if {@code lineNames} is neither empty nor
     *                                  {@code tracks.size() + 1} sets long
     */
    public GridRepetition withLineNames(List<List<String>> lineNames) {
        return new GridRepetition(type, count, tracks, lineNames);
    }
    
    private static List<List<String>> validatedLineNames(List<List<String>> lineNames, int trackCount) {
        if (lineNames == null || lineNames.isEmpty()) {
            return List.of();
        }
        if (lineNames.size() != trackCount + 1) {
            throw new IllegalArgumentException(
                "grid template repetition must have no line name sets or exactly track count + 1 of them ("
                + trackCount + " tracks but " + lineNames.size() + " line name sets)");
        }
        List<List<String>> copy = new ArrayList<>(lineNames.size());
        for (List<String> names : lineNames) {
            copy.add(names == null ? List.of() : List.copyOf(names));
        }
        return List.copyOf(copy);
    }
    
    public RepetitionType getType() {
        return type;
    }
    
    public int getCount() {
        return count;
    }
    
    public List<TrackSizingFunction> getTracks() {
        return tracks;
    }
    
    /**
     * Positional line names for the lines generated by one repetition of this repetition.
     * Empty when the repeated lines are unnamed, otherwise exactly {@code getTrackCount() + 1}
     * name sets (one per line, including both edge lines). The outer and inner lists are immutable.
     */
    public List<List<String>> getLineNames() {
        return lineNames;
    }
    
    /**
     * Whether this repetition declares line names for the lines it generates.
     */
    public boolean hasLineNames() {
        return !lineNames.isEmpty();
    }
    
    public int getTrackCount() {
        return tracks.size();
    }
    
    public boolean isAutoRepetition() {
        return type == RepetitionType.AUTO_FILL || type == RepetitionType.AUTO_FIT;
    }
    
    /**
     * Checks if all tracks in this repetition have a fixed component.
     * Required for auto-fill/auto-fit to work correctly.
     */
    public boolean hasFixedComponent() {
        return tracks.stream().allMatch(TrackSizingFunction::hasFixedComponent);
    }

    @Override
    public boolean equals(Object o) {
        if (this == o) return true;
        if (o == null || getClass() != o.getClass()) return false;
        GridRepetition that = (GridRepetition) o;
        if (type != that.type) return false;
        if (count != that.count) return false;
        if (!Objects.equals(tracks, that.tracks)) return false;
        return Objects.equals(lineNames, that.lineNames);
    }

    @Override
    public int hashCode() {
        int result = type.hashCode();
        result = 31 * result + count;
        result = 31 * result + (tracks != null ? tracks.hashCode() : 0);
        result = 31 * result + (lineNames != null ? lineNames.hashCode() : 0);
        return result;
    }
}
